#!/usr/bin/env python3
"""Adopt tested main-branch revisions of the dotfiles and Myfish repositories.

Each repository exports a toolbox.json. Its built-in entries name an installer
under scripts/installers/commander; its config entries become generated
wrappers around catalog-install.sh. Both become catalog files, one per entry,
in the area that owns them. The revision pins live in common.sh.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from urllib.parse import urlencode
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
INSTALLERS = ROOT / 'scripts/installers/commander'
CATALOG = ROOT / 'catalog'
sys.path.insert(0, str(INSTALLERS))
from catalog import source_path, validate  # noqa: E402

SOURCES = ('Myfish', 'dotfiles')
GENERATED_NOTE = '# Generated by scripts/sync-sources.py from {source}/toolbox.json; edit that file instead.\n'

# Where each built-in handler's entry lives, what it writes, and what it needs.
BUILTINS = {
    'dotfiles-nvim': ('configurations/dotfiles', ['~/.config/nvim'], [], 'I FM MP'),
    'dotfiles-fastfetch': ('configurations/dotfiles', ['~/.config/fastfetch', '~/.local/bin/fastfetch'], [], 'I FM MP'),
    'dotfiles-starship': ('configurations/dotfiles', ['~/.config/starship.toml'], [], 'I FM MP'),
    'dotfiles-konsole': ('configurations/dotfiles', ['~/.local/share/konsole/Garuda.profile', '~/.local/share/konsole/Sweet.colorscheme'], [], 'I FM MP'),
    'dotfiles-ghostty': ('configurations/dotfiles', ['~/.config/ghostty/config', '~/.config/ghostty/spotatui.conf', '~/.config/ghostty/themes/commander', '~/.config/ghostty/topbar.css'], [], 'I FM MP'),
    'zellij': ('applications/terminal-tools', ['~/.config/zellij/config.kdl'], [], 'I FM MP'),
    'netwatch': ('applications/terminal-tools', [], ['nix', 'git'], 'FM MP'),
    'tfm': ('applications/terminal-tools', [], ['nix', 'git'], 'FM MP'),
    'cassette': ('applications/terminal-tools', [], ['nix', 'git'], 'FM MP'),
    'myfish-fish': ('configurations/myfish', [], [], 'I FM MP'),
    'myfish-bash': ('configurations/myfish', [], [], 'I FM MP'),
    'myfish-zsh': ('configurations/myfish', [], [], 'I FM MP'),
    'myfish': ('configurations/myfish', [], [], 'I FM MP'),
}
CONFIG_AREA = {'dotfiles': 'configurations/dotfiles', 'Myfish': 'configurations/myfish'}


def api(path):
    headers = {'Accept': 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28'}
    if os.environ.get('GH_TOKEN'):
        headers['Authorization'] = 'Bearer ' + os.environ['GH_TOKEN']
    request = Request('https://api.github.com/' + path, headers=headers)
    with urlopen(request, timeout=30) as response:
        return json.load(response)


def eligible_revision(source, request=api):
    repo = f'Commanderx-code/{source}'
    head = request(f'repos/{repo}/commits/main')['sha']
    if not re.fullmatch(r'[0-9a-f]{40}', head):
        raise ValueError('GitHub returned an invalid revision.')
    query = urlencode({'branch': 'main', 'head_sha': head, 'per_page': 100})
    runs = request(f'repos/{repo}/actions/workflows/check.yml/runs?{query}')['workflow_runs']
    # Do not filter for success in the API: a newer failed rerun must veto an older success.
    runs = [r for r in runs if r['head_sha'] == head and r['event'] in ('push', 'workflow_dispatch')
            and r['head_branch'] == 'main' and r['head_repository']['full_name'] == repo]
    latest = max(runs, key=lambda r: (r['id'], r.get('run_attempt', 1)), default=None)
    if latest and latest['status'] == 'completed' and latest['conclusion'] == 'success':
        return head
    print(f'{source}: waiting for successful check.yml on {head[:12]}.')
    return None


def checkout(source, revision, destination):
    subprocess.run(['git', 'init', '-q', str(destination)], check=True)
    subprocess.run(['git', '-C', str(destination), 'fetch', '--quiet', '--depth=1',
                    f'https://github.com/Commanderx-code/{source}.git', revision], check=True)
    subprocess.run(['git', '-C', str(destination), 'checkout', '--quiet', '--detach', 'FETCH_HEAD'], check=True)


def validate_checkout(source, root, document):
    entries = validate(document, source, root)
    # Check the contract of existing consumers as well as new generic exports.
    if source == 'Myfish':
        for path in ('install.sh', 'scripts/bootstrap.py', 'scripts/native.py', 'modules/home.nix'):
            source_path(root, path)
        subprocess.run(['bash', '-n', str(root / 'install.sh')], check=True)
    else:
        required = {
            'dotfiles-nvim': ['configs/nvim/init.lua'],
            'dotfiles-fastfetch': ['configs/fastfetch/config.jsonc', 'configs/fastfetch/png/arch.png'],
            'dotfiles-starship': ['configs/starship/starship.toml'],
            'dotfiles-konsole': ['configs/konsole/Garuda.profile', 'configs/konsole/Sweet.colorscheme'],
            'dotfiles-ghostty': ['configs/ghostty/config', 'configs/ghostty/spotatui.conf', 'configs/themes/eldritch.json'],
            'zellij': [],
            'netwatch': ['home-manager/flake.nix', 'home-manager/terminal-tools.nix'],
            'tfm': ['home-manager/flake.nix', 'home-manager/terminal-tools.nix'],
            'cassette': ['home-manager/flake.nix', 'home-manager/terminal-tools.nix'],
        }
        for entry in entries:
            if entry['type'] == 'builtin':
                for path in required[entry['handler']]:
                    source_path(root, path)
        # These integrations consume the same dotfiles pin outside the exported entries.
        for path in ('configs/topgrade/topgrade.toml', 'sddm/metadata.desktop', 'sddm/configs/kratos.conf',
                     'sddm/sddm-conf/20-silent.conf', 'plymouth/theme', 'grub/themes/cachyos/theme.txt',
                     'limine/themes/cachyos/limine.conf', 'limine/themes/garuda/limine.conf'):
            source_path(root, path)


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)


def render_entry(source, entry, order):
    """The catalog file for one exported entry: (relative path, text)."""
    if entry['type'] == 'builtin':
        handler = entry['handler']
        if not (INSTALLERS / f'{handler}.sh').is_file():
            raise ValueError(f'Missing built-in installer: {handler}.sh')
        area, writes, needs, flags = BUILTINS[handler]
        script_id = f'commander/{handler}'
        path = f'{area}/{handler}.toml'
    else:
        area = CONFIG_AREA[source]
        writes = [f'~/.config/{file["target"]}' for file in entry['files']]
        needs = []
        flags = 'I FM MP'
        script_id = f'commander/generated/{source.lower()}-{entry["id"]}'
        path = f'{area}/{source.lower()}-{entry["id"]}.toml'
    text = GENERATED_NOTE.format(source=source)
    text += f'name = {toml_string(entry["name"])}\n'
    text += f'description = {toml_string(entry["description"])}\n'
    text += f'flags = {toml_string(flags)}\n'
    text += 'multi_select = false\n'
    text += f'order = {order}\n'
    if writes:
        text += 'writes = [' + ', '.join(toml_string(w) for w in writes) + ']\n'
    if needs:
        text += '\n[[preconditions]]\nmatches = true\ncheck = "command_exists"\nvalues = [' + ', '.join(toml_string(n) for n in needs) + ']\n'
    text += f'\n[script]\nid = {toml_string(script_id)}\n'
    return path, text


def render(documents):
    """Catalog files and generated wrappers for every source: ({path: text}, {name: text})."""
    files, wrappers, names = {}, {}, set()
    for source in SOURCES:
        entries = validate(documents[source], source)
        for order, entry in enumerate(entries, 1):
            if entry['name'] in names:
                raise ValueError('Menu names must be unique across source catalogs.')
            names.add(entry['name'])
            path, text = render_entry(source, entry, order)
            files[path] = text
            if entry['type'] == 'config':
                name = f'{source.lower()}-{entry["id"]}.sh'
                wrappers[name] = (f'#!/bin/sh -e\n# Generated from {source}/toolbox.json.\n'
                                  f'cd ..\nexec sh -e ./catalog-install.sh {source} {entry["id"]}\n')
    return files, wrappers


def publish_files(documents, revisions):
    files, wrappers = render(documents)
    # Entries this script owns carry the generated note; stale ones are removed.
    for area in set(CONFIG_AREA.values()) | {area for area, _, _, _ in BUILTINS.values()}:
        directory = CATALOG / area
        if directory.is_dir():
            for path in directory.glob('*.toml'):
                if path.read_text().startswith('# Generated by scripts/sync-sources.py') and str(path.relative_to(CATALOG)) not in files:
                    path.unlink()
    for path, text in files.items():
        target = CATALOG / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    common_path = INSTALLERS / 'common.sh'
    common = common_path.read_text()
    for source, revision in revisions.items():
        if source not in SOURCES or not re.fullmatch(r'[0-9a-f]{40}', revision):
            raise ValueError('Invalid source pin.')
        common, count = re.subn(rf'({source}\) revision=)[0-9a-f]{{40}}( ;;)', rf'\g<1>{revision}\2', common)
        if count != 1:
            raise ValueError(f'Missing unique source pin: {source}')
    common_path.write_text(common)
    for source, document in documents.items():
        (INSTALLERS / 'catalogs' / f'{source}.json').write_text(json.dumps(document, indent=2) + '\n')
    generated = INSTALLERS / 'generated'
    generated.mkdir(exist_ok=True)
    for path in generated.glob('*.sh'):
        if path.name not in wrappers:
            path.unlink()
    for name, content in wrappers.items():
        (generated / name).write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true', help='regenerate from the embedded catalogs, without network access')
    args = parser.parse_args()
    documents = {source: json.loads((INSTALLERS / 'catalogs' / f'{source}.json').read_text()) for source in SOURCES}
    revisions = {}
    if not args.render:
        with tempfile.TemporaryDirectory(prefix='helixforge-sync-') as temporary:
            for source in SOURCES:
                revision = eligible_revision(source)
                if revision is None:
                    continue
                destination = Path(temporary) / source
                checkout(source, revision, destination)
                document = json.loads((destination / 'toolbox.json').read_text())
                validate_checkout(source, destination, document)
                documents[source], revisions[source] = document, revision
                print(f'{source}: adopting tested revision {revision}.')
    publish_files(documents, revisions)
    if os.environ.get('GITHUB_OUTPUT'):
        changed = subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=all'], cwd=ROOT, text=True)
        with open(os.environ['GITHUB_OUTPUT'], 'a') as output:
            output.write(f'changed={str(bool(changed)).lower()}\n')


if __name__ == '__main__':
    main()
